"""What are Modules
•	A module is like a code library that can be used to borrow code written by somebody else. In our Python program
•	There are two types of modules
1.	Built-in modules
2.	External modules
Built-in module-  These modules are ready to import and use, and ship with the Python interpreter. There is no need to install such modules explicitly.
External module- These modules are imported from a third-party file or can be installed using a package manager like pip and conda. Since this code is written by someone else, we can install different versions of the same module over time """
